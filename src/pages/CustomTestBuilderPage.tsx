import { useState, useEffect, useMemo } from 'react';
import { useNavigate } from 'react-router-dom';
import Navbar from '../components/Navbar';
import { fetchHierarchy, fetchQuestions, generateCustomTest } from '../utils/api';
import type {
  SubjectWithTopics,
  QuestionBankItem,
  TestData,
  TestMode,
  QuestionType,
  MarkValue,
} from '../types';
import { calculateDuration, formatDurationHuman } from '../utils/scoring';
import RichContent from '../components/RichContent';
import { QuestionImage } from '../components/ImageLightbox';
import TikzDiagram from '../components/TikzDiagram';
import {
  Wrench,
  Play,
  Download,
  Search,
  CheckSquare,
  Square,
  Sparkles,
  Clock,
  Plus,
  Trash2,
  AlertCircle,
} from 'lucide-react';
import { useAuth } from '../context/AuthContext';
import { PaymentModal } from '../components/PaymentModal';

type BuilderMode = 'manual' | 'rules' | 'full-mock';

interface MixRule {
  id: string;
  subjectId?: number;
  topicId?: number;
  type?: QuestionType;
  marks?: MarkValue;
  count: number;
}

export default function CustomTestBuilderPage() {
  const navigate = useNavigate();
  const { user } = useAuth();
  const [showPaymentModal, setShowPaymentModal] = useState(false);

  const [builderMode, setBuilderMode] = useState<BuilderMode>('manual');
  const [hierarchy, setHierarchy] = useState<SubjectWithTopics[]>([]);
  const [allQuestions, setAllQuestions] = useState<QuestionBankItem[]>([]);
  const [loading, setLoading] = useState(true);

  // Test Paper Config
  const [testTitle, setTestTitle] = useState('Abhiyantra GATE Mock Test');
  const [testDesc, setTestDesc] = useState('Custom test paper generated by Abhiyantra Question Bank.');
  const [testMode, setTestMode] = useState<TestMode>('exam');

  // Manual Mode State: selected question IDs
  const [selectedIds, setSelectedIds] = useState<Set<number>>(new Set());
  const [searchFilter, setSearchFilter] = useState('');
  const [subjectFilter, setSubjectFilter] = useState<number | ''>('');
  const [typeFilter, setTypeFilter] = useState<QuestionType | ''>('');
  const [marksFilter, setMarksFilter] = useState<MarkValue | ''>('');

  // Full Mock Mode State
  const [mockSubjectId, setMockSubjectId] = useState<number | ''>('');

  // Bucket calculations for Full Mock
  const gaQuestions = useMemo(() => {
    return allQuestions.filter(
      (q) => q.section === 'GA' || q.subject.name.toLowerCase().includes('general aptitude')
    );
  }, [allQuestions]);

  const coreQuestions = useMemo(() => {
    const nonGA = allQuestions.filter(
      (q) => !(q.section === 'GA' || q.subject.name.toLowerCase().includes('general aptitude'))
    );
    if (!mockSubjectId) return nonGA;
    return nonGA.filter((q) => q.subjectId === mockSubjectId);
  }, [allQuestions, mockSubjectId]);

  const ga1m = useMemo(() => gaQuestions.filter((q) => q.marks === 1), [gaQuestions]);
  const ga2m = useMemo(() => gaQuestions.filter((q) => q.marks === 2), [gaQuestions]);
  const core1m = useMemo(() => coreQuestions.filter((q) => q.marks === 1), [coreQuestions]);
  const core2m = useMemo(() => coreQuestions.filter((q) => q.marks === 2), [coreQuestions]);

  const totalMockAvailable = ga1m.length + ga2m.length + core1m.length + core2m.length;
  const isFull65Available =
    ga1m.length >= 5 &&
    ga2m.length >= 5 &&
    core1m.length >= 25 &&
    core2m.length >= 30;

  // Rules Mode State
  const [rules, setRules] = useState<MixRule[]>([
    { id: '1', count: 5 },
  ]);

  // Loading state when launching or exporting
  const [generating, setGenerating] = useState(false);
  const [errorMsg, setErrorMsg] = useState('');

  // Load question bank questions & hierarchy
  useEffect(() => {
    async function init() {
      try {
        setLoading(true);
        const [hier, qs] = await Promise.all([
          fetchHierarchy(),
          fetchQuestions({ includeArchived: false }),
        ]);
        setHierarchy(hier);
        setAllQuestions(qs);
        // Pre-select first 5 questions if available
        if (qs.length > 0) {
          setSelectedIds(new Set(qs.slice(0, Math.min(5, qs.length)).map((q) => q.id)));
        }
      } catch (err) {
        console.error('Failed to load builder data:', err);
      } finally {
        setLoading(false);
      }
    }
    init();
  }, []);

  // Filtered list of questions for manual selection
  const filteredQuestions = useMemo(() => {
    return allQuestions.filter((q) => {
      if (searchFilter && !q.questionText.toLowerCase().includes(searchFilter.toLowerCase())) {
        return false;
      }
      if (subjectFilter !== '' && q.subjectId !== subjectFilter) {
        return false;
      }
      if (typeFilter !== '' && q.type !== typeFilter) {
        return false;
      }
      if (marksFilter !== '' && q.marks !== marksFilter) {
        return false;
      }
      return true;
    });
  }, [allQuestions, searchFilter, subjectFilter, typeFilter, marksFilter]);

  // Currently selected questions list
  const selectedQuestionsList = useMemo(() => {
    const set = selectedIds;
    return allQuestions.filter((q) => set.has(q.id));
  }, [allQuestions, selectedIds]);

  // Computed summary metrics
  const totalQuestions = selectedQuestionsList.length;
  const totalMarks = selectedQuestionsList.reduce((sum, q) => sum + q.marks, 0);
  const totalDuration = calculateDuration(totalQuestions);

  const typeCounts = useMemo(() => {
    const counts = { MCQ: 0, MSQ: 0, NAT: 0 };
    selectedQuestionsList.forEach((q) => {
      counts[q.type]++;
    });
    return counts;
  }, [selectedQuestionsList]);

  const subjectCounts = useMemo(() => {
    const map = new Map<string, number>();
    selectedQuestionsList.forEach((q) => {
      map.set(q.subject.name, (map.get(q.subject.name) || 0) + 1);
    });
    return Array.from(map.entries());
  }, [selectedQuestionsList]);

  // Toggle single question selection
  const toggleQuestionSelection = (id: number) => {
    setSelectedIds((prev) => {
      const next = new Set(prev);
      if (next.has(id)) next.delete(id);
      else next.add(id);
      return next;
    });
  };

  // Select all visible questions
  const selectAllVisible = () => {
    setSelectedIds((prev) => {
      const next = new Set(prev);
      filteredQuestions.forEach((q) => next.add(q.id));
      return next;
    });
  };

  // Deselect all visible questions
  const deselectAllVisible = () => {
    setSelectedIds((prev) => {
      const next = new Set(prev);
      filteredQuestions.forEach((q) => next.delete(q.id));
      return next;
    });
  };

  // Add rule in Rules Mode
  const addRule = () => {
    setRules((prev) => [
      ...prev,
      { id: String(Date.now()), count: 3 },
    ]);
  };

  const removeRule = (id: string) => {
    setRules((prev) => prev.filter((r) => r.id !== id));
  };

  const updateRule = (id: string, patch: Partial<MixRule>) => {
    setRules((prev) =>
      prev.map((r) => (r.id === id ? { ...r, ...patch } : r))
    );
  };

  // Build the TestData object (manual selections, rules mix, or official full mock)
  const buildTestData = async (): Promise<TestData> => {
    if (builderMode === 'full-mock') {
      const shuffle = <T,>(arr: T[]): T[] => [...arr].sort(() => 0.5 - Math.random());

      const selectedGa1 = shuffle(ga1m).slice(0, 5);
      const selectedGa2 = shuffle(ga2m).slice(0, 5);
      const selectedCore1 = shuffle(core1m).slice(0, 25);
      const selectedCore2 = shuffle(core2m).slice(0, 30);

      const combined = [
        ...selectedGa1.map((q) => ({ ...q, section: 'GA' as const })),
        ...selectedGa2.map((q) => ({ ...q, section: 'GA' as const })),
        ...selectedCore1.map((q) => ({ ...q, section: 'SUBJECT' as const })),
        ...selectedCore2.map((q) => ({ ...q, section: 'SUBJECT' as const })),
      ];

      if (combined.length === 0) {
        throw new Error('No questions available in the question bank to generate a full mock test.');
      }

      const totalMarks = combined.reduce((acc, q) => acc + q.marks, 0);

      return {
        title: testTitle.trim() || `Official GATE Mock Test (${combined.length} Qs / ${totalMarks} Marks)`,
        subject: mockSubjectId ? hierarchy.find((s) => s.id === mockSubjectId)?.name : 'Official GATE Pattern',
        description: testDesc.trim() || `Official GATE Examination structure with General Aptitude (Section 1) and Core Subject (Section 2).`,
        sections: [
          {
            id: 'GA',
            name: 'Section 1: General Aptitude',
            questionCount: selectedGa1.length + selectedGa2.length,
            marks: selectedGa1.length * 1 + selectedGa2.length * 2,
          },
          {
            id: 'SUBJECT',
            name: `Section 2: ${mockSubjectId ? hierarchy.find((s) => s.id === mockSubjectId)?.name : 'Core Subject'}`,
            questionCount: selectedCore1.length + selectedCore2.length,
            marks: selectedCore1.length * 1 + selectedCore2.length * 2,
          },
        ],
        questions: combined.map((q, idx) => ({
          id: idx + 1,
          section: q.section,
          subject: q.subject.name,
          topic: q.topic.name,
          type: q.type,
          marks: q.marks,
          question: q.questionText,
          options: q.options,
          answer: q.answer,
          solution: q.solution,
          imageUrl: q.imageUrl,
          tikzCode: q.tikzCode,
          solutionImageUrl: q.solutionImageUrl,
          solutionTikzCode: q.solutionTikzCode,
        })),
      };
    } else if (builderMode === 'manual') {
      if (selectedQuestionsList.length === 0) {
        throw new Error('Please select at least 1 question to build a test.');
      }
      return {
        title: testTitle.trim() || 'Custom GATE Mock Test',
        description: testDesc.trim(),
        questions: selectedQuestionsList.map((q, idx) => ({
          id: idx + 1,
          subject: q.subject.name,
          topic: q.topic.name,
          type: q.type,
          marks: q.marks,
          question: q.questionText,
          options: q.options,
          answer: q.answer,
          solution: q.solution,
          imageUrl: q.imageUrl,
          tikzCode: q.tikzCode,
          solutionImageUrl: q.solutionImageUrl,
          solutionTikzCode: q.solutionTikzCode,
        })),
      };
    } else {
      // Rules Mode: call backend generator
      return await generateCustomTest({
        title: testTitle.trim(),
        description: testDesc.trim(),
        rules: rules.map((r) => ({
          subjectId: r.subjectId,
          topicId: r.topicId,
          type: r.type,
          marks: r.marks,
          count: r.count,
        })),
      });
    }
  };

  // Action: Launch Test directly in /test
  const handleLaunchTest = async () => {
    setErrorMsg('');
    try {
      setGenerating(true);
      const testData = await buildTestData();

      // Freemium Gatekeeper: tests with > 15 questions or full mock tests require active pass
      if ((builderMode === 'full-mock' || testData.questions.length > 15) && !user?.isSubscribed) {
        setShowPaymentModal(true);
        setGenerating(false);
        return;
      }

      navigate('/test', { state: { testData, mode: testMode } });
    } catch (err: unknown) {
      setErrorMsg((err as Error).message || 'Failed to generate test.');
    } finally {
      setGenerating(false);
    }
  };

  // Action: Export Test as .json file
  const handleExportJSON = async () => {
    setErrorMsg('');
    try {
      setGenerating(true);
      const testData = await buildTestData();
      const blob = new Blob([JSON.stringify(testData, null, 2)], { type: 'application/json' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `${testTitle.toLowerCase().replace(/[^a-z0-9]+/g, '-')}.json`;
      a.click();
      URL.revokeObjectURL(url);
    } catch (err: unknown) {
      setErrorMsg((err as Error).message || 'Failed to export test.');
    } finally {
      setGenerating(false);
    }
  };

  return (
    <div className="min-h-screen bg-slate-50 flex flex-col">
      <Navbar />

      {/* ─── Hero / Header ─── */}
      <header className="bg-gradient-to-r from-indigo-900 via-indigo-800 to-blue-900 text-white py-8 px-4 sm:px-6 lg:px-8 shadow-md">
        <div className="max-w-7xl mx-auto flex flex-col md:flex-row md:items-center md:justify-between gap-4">
          <div className="flex items-center gap-4">
            <img
              src="/logo.avif"
              alt="Abhiyantra Logo"
              className="w-12 h-12 object-contain rounded-xl bg-white/10 p-1.5 border border-white/20 shadow-sm shrink-0"
            />
            <div>
              <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-indigo-500/30 text-indigo-200 text-xs font-semibold mb-1 border border-indigo-400/30">
                <Wrench className="w-3.5 h-3.5" />
                <span className="capitalize">abhiyantra</span> • Custom Paper Synthesis
              </div>
              <h1 className="text-2xl sm:text-3xl font-extrabold tracking-tight">Abhiyantra Test Builder</h1>
              <p className="mt-0.5 text-xs text-indigo-200 max-w-2xl">
                Assemble custom mock tests from your Question Bank or generate an automated syllabus mix.
              </p>
            </div>
          </div>

          {/* Builder Mode Switcher */}
          <div className="flex flex-wrap items-center bg-white/10 p-1.5 rounded-2xl border border-white/20 backdrop-blur-xs gap-1.5">
            <button
              onClick={() => setBuilderMode('manual')}
              className={`px-3.5 py-2 rounded-xl text-xs font-bold transition-all ${
                builderMode === 'manual'
                  ? 'bg-white text-indigo-900 shadow-sm'
                  : 'text-white/80 hover:text-white'
              }`}
            >
              Pick &amp; Choose
            </button>
            <button
              onClick={() => setBuilderMode('rules')}
              className={`px-3.5 py-2 rounded-xl text-xs font-bold transition-all ${
                builderMode === 'rules'
                  ? 'bg-white text-indigo-900 shadow-sm'
                  : 'text-white/80 hover:text-white'
              }`}
            >
              Rule Mix
            </button>
            <button
              onClick={() => {
                setBuilderMode('full-mock');
                setTestTitle('Official GATE Full Mock Test (65 Qs / 100 Marks / 180 Min)');
                setTestDesc('Official 65-question GATE CBT pattern: 10 General Aptitude + 55 Core Subject questions.');
              }}
              className={`px-3.5 py-2 rounded-xl text-xs font-bold transition-all flex items-center gap-1.5 ${
                builderMode === 'full-mock'
                  ? 'bg-amber-400 text-slate-950 shadow-sm ring-1 ring-amber-300 font-extrabold'
                  : 'text-amber-200 hover:text-white'
              }`}
            >
              <Sparkles className="w-3.5 h-3.5" />
              Official GATE Full Mock (65 Qs)
            </button>
          </div>
        </div>
      </header>

      {/* ─── Main Content ─── */}
      <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-8 w-full flex-1 flex flex-col lg:flex-row gap-6">
        {/* ─── LEFT PANEL: Question Selection or Rule Configuration ─── */}
        <div className="flex-1 space-y-4">
          {errorMsg && (
            <div className="p-4 bg-red-50 border border-red-200 text-red-700 rounded-2xl text-sm font-semibold flex items-center gap-2">
              <AlertCircle className="w-5 h-5 shrink-0" />
              {errorMsg}
            </div>
          )}

          {/* ══════════ MODE A: Pick & Choose (Manual Selection) ══════════ */}
          {builderMode === 'manual' && (
            <div className="space-y-4">
              {/* Filter and Bulk Selection Bar */}
              <div className="bg-white rounded-2xl border border-slate-200 shadow-xs p-4 space-y-3">
                <div className="flex flex-wrap items-center gap-3">
                  {/* Search */}
                  <div className="relative flex-1 min-w-[200px]">
                    <Search className="w-4 h-4 text-slate-400 absolute left-3 top-3" />
                    <input
                      type="text"
                      placeholder="Search question text..."
                      value={searchFilter}
                      onChange={(e) => setSearchFilter(e.target.value)}
                      className="w-full pl-9 pr-3 py-2 text-sm bg-slate-50 border border-slate-200 rounded-xl focus:bg-white focus:outline-none focus:ring-2 focus:ring-indigo-400"
                    />
                  </div>

                  {/* Subject filter */}
                  <select
                    value={subjectFilter}
                    onChange={(e) => setSubjectFilter(e.target.value ? Number(e.target.value) : '')}
                    className="w-full sm:w-auto px-3 py-2 text-sm bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-indigo-400"
                  >
                    <option value="">All Subjects</option>
                    {hierarchy.map((s) => (
                      <option key={s.id} value={s.id}>
                        {s.name}
                      </option>
                    ))}
                  </select>

                  {/* Type filter */}
                  <select
                    value={typeFilter}
                    onChange={(e) => setTypeFilter(e.target.value as QuestionType | '')}
                    className="w-full sm:w-auto px-3 py-2 text-sm bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-indigo-400"
                  >
                    <option value="">All Types</option>
                    <option value="MCQ">MCQ</option>
                    <option value="MSQ">MSQ</option>
                    <option value="NAT">NAT</option>
                  </select>

                  {/* Marks filter */}
                  <select
                    value={marksFilter}
                    onChange={(e) => setMarksFilter(e.target.value ? (Number(e.target.value) as MarkValue) : '')}
                    className="w-full sm:w-auto px-3 py-2 text-sm bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-indigo-400"
                  >
                    <option value="">All Marks</option>
                    <option value="1">1-Mark</option>
                    <option value="2">2-Marks</option>
                  </select>
                </div>

                {/* Bulk Actions */}
                <div className="flex items-center justify-between pt-2 border-t border-slate-100 text-xs">
                  <span className="font-semibold text-slate-500">
                    Showing {filteredQuestions.length} questions ({selectedIds.size} selected)
                  </span>
                  <div className="flex items-center gap-2">
                    <button
                      onClick={selectAllVisible}
                      className="px-3 py-1 bg-indigo-50 text-indigo-700 font-semibold rounded-lg hover:bg-indigo-100 transition-colors"
                    >
                      Select All Filtered
                    </button>
                    <button
                      onClick={deselectAllVisible}
                      className="px-3 py-1 bg-slate-100 text-slate-600 font-semibold rounded-lg hover:bg-slate-200 transition-colors"
                    >
                      Deselect Filtered
                    </button>
                  </div>
                </div>
              </div>

              {/* Questions List with Checkboxes */}
              {loading ? (
                <div className="bg-white rounded-2xl border border-slate-200 p-12 text-center text-slate-400">
                  Loading available questions...
                </div>
              ) : filteredQuestions.length === 0 ? (
                <div className="bg-white rounded-2xl border border-slate-200 p-12 text-center text-slate-400">
                  No questions match your current filters.
                </div>
              ) : (
                <div className="space-y-3">
                  {filteredQuestions.map((q) => {
                    const isSelected = selectedIds.has(q.id);
                    return (
                      <div
                        key={q.id}
                        onClick={() => toggleQuestionSelection(q.id)}
                        className={`p-4 bg-white rounded-2xl border cursor-pointer transition-all ${
                          isSelected
                            ? 'border-indigo-500 ring-2 ring-indigo-200 bg-indigo-50/20'
                            : 'border-slate-200 hover:border-slate-300'
                        }`}
                      >
                        <div className="flex items-start gap-3">
                          <button
                            type="button"
                            className="mt-0.5 text-indigo-600 shrink-0"
                            onClick={(e) => {
                              e.stopPropagation();
                              toggleQuestionSelection(q.id);
                            }}
                          >
                            {isSelected ? (
                              <CheckSquare className="w-5 h-5 text-indigo-600" />
                            ) : (
                              <Square className="w-5 h-5 text-slate-300 hover:text-slate-400" />
                            )}
                          </button>

                          <div className="flex-1 space-y-2">
                            <div className="flex flex-wrap items-center gap-2">
                              <span
                                className={`px-2 py-0.5 rounded-full text-xs font-bold ${
                                  q.type === 'MCQ'
                                    ? 'bg-blue-100 text-blue-800'
                                    : q.type === 'MSQ'
                                    ? 'bg-purple-100 text-purple-800'
                                    : 'bg-emerald-100 text-emerald-800'
                                }`}
                              >
                                {q.type}
                              </span>
                              <span className="px-2 py-0.5 rounded-full text-xs font-semibold bg-slate-100 text-slate-600">
                                {q.marks} Mark{q.marks > 1 ? 's' : ''}
                              </span>
                              <span className="px-2 py-0.5 rounded-full text-xs font-semibold bg-indigo-50 text-indigo-700 border border-indigo-200">
                                {q.subject.name}
                              </span>
                              <span className="px-2 py-0.5 rounded-full text-xs font-semibold bg-slate-100 text-slate-600">
                                {q.topic.name}
                              </span>
                            </div>

                            {q.imageUrl && (
                              <div className="max-w-xs my-2">
                                <QuestionImage src={q.imageUrl} alt="Question Diagram" />
                              </div>
                            )}
                            {q.tikzCode && (
                              <div className="max-w-xs my-2">
                                <TikzDiagram code={q.tikzCode} />
                              </div>
                            )}
                            <div className="text-sm font-medium text-slate-800 leading-relaxed">
                              <RichContent content={q.questionText} />
                            </div>
                          </div>
                        </div>
                      </div>
                    );
                  })}
                </div>
              )}
            </div>
          )}

          {/* ══════════ MODE B: Rule-Based Syllabus Mix ══════════ */}
          {builderMode === 'rules' && (
            <div className="bg-white rounded-2xl border border-slate-200 shadow-xs p-6 space-y-6">
              <div>
                <h3 className="text-base font-bold text-slate-800 flex items-center gap-2">
                  <Sparkles className="w-5 h-5 text-indigo-600" />
                  Automated Syllabus Distribution Blueprint
                </h3>
                <p className="text-xs text-slate-500 mt-1">
                  Define mix rules (e.g. 5 questions from Data Structures, 3 questions from Operating Systems). The generator samples matching questions randomly from your database.
                </p>
              </div>

              <div className="space-y-3">
                {rules.map((rule, idx) => {
                  const matchingTopics = rule.subjectId
                    ? hierarchy.find((s) => s.id === rule.subjectId)?.topics || []
                    : [];

                  return (
                    <div
                      key={rule.id}
                      className="p-4 bg-slate-50 border border-slate-200 rounded-xl space-y-3"
                    >
                      <div className="flex items-center justify-between text-xs font-bold text-slate-700">
                        <span>Rule #{idx + 1}</span>
                        {rules.length > 1 && (
                          <button
                            type="button"
                            onClick={() => removeRule(rule.id)}
                            className="text-red-500 hover:text-red-700 p-1"
                          >
                            <Trash2 className="w-4 h-4" />
                          </button>
                        )}
                      </div>

                      <div className="grid grid-cols-1 sm:grid-cols-4 gap-3 text-xs">
                        {/* Subject */}
                        <div className="sm:col-span-1">
                          <label className="block text-[11px] font-bold text-slate-600 mb-1">Subject</label>
                          <select
                            value={rule.subjectId || ''}
                            onChange={(e) =>
                              updateRule(rule.id, {
                                subjectId: e.target.value ? Number(e.target.value) : undefined,
                                topicId: undefined,
                              })
                            }
                            className="w-full px-2.5 py-1.5 border border-slate-300 rounded-lg bg-white"
                          >
                            <option value="">Any Subject</option>
                            {hierarchy.map((s) => (
                              <option key={s.id} value={s.id}>
                                {s.name}
                              </option>
                            ))}
                          </select>
                        </div>

                        {/* Topic */}
                        <div className="sm:col-span-1">
                          <label className="block text-[11px] font-bold text-slate-600 mb-1">Topic</label>
                          <select
                            value={rule.topicId || ''}
                            onChange={(e) =>
                              updateRule(rule.id, {
                                topicId: e.target.value ? Number(e.target.value) : undefined,
                              })
                            }
                            disabled={!rule.subjectId}
                            className="w-full px-2.5 py-1.5 border border-slate-300 rounded-lg bg-white disabled:bg-slate-100 disabled:text-slate-400"
                          >
                            <option value="">Any Topic</option>
                            {matchingTopics.map((t) => (
                              <option key={t.id} value={t.id}>
                                {t.name}
                              </option>
                            ))}
                          </select>
                        </div>

                        {/* Type & Marks */}
                        <div className="sm:col-span-1">
                          <label className="block text-[11px] font-bold text-slate-600 mb-1">Type &amp; Marks</label>
                          <div className="grid grid-cols-2 gap-1">
                            <select
                              value={rule.type || ''}
                              onChange={(e) =>
                                updateRule(rule.id, {
                                  type: e.target.value ? (e.target.value as QuestionType) : undefined,
                                })
                              }
                              className="w-full px-1.5 py-1.5 border border-slate-300 rounded-lg bg-white"
                            >
                              <option value="">Any</option>
                              <option value="MCQ">MCQ</option>
                              <option value="MSQ">MSQ</option>
                              <option value="NAT">NAT</option>
                            </select>

                            <select
                              value={rule.marks || ''}
                              onChange={(e) =>
                                updateRule(rule.id, {
                                  marks: e.target.value ? (Number(e.target.value) as MarkValue) : undefined,
                                })
                              }
                              className="w-full px-1.5 py-1.5 border border-slate-300 rounded-lg bg-white"
                            >
                              <option value="">Any</option>
                              <option value="1">1M</option>
                              <option value="2">2M</option>
                            </select>
                          </div>
                        </div>

                        {/* Count */}
                        <div className="sm:col-span-1">
                          <label className="block text-[11px] font-bold text-slate-600 mb-1">Questions</label>
                          <input
                            type="number"
                            min={1}
                            max={65}
                            value={rule.count}
                            onChange={(e) => updateRule(rule.id, { count: Math.max(1, Number(e.target.value)) })}
                            className="w-full px-2.5 py-1.5 border border-slate-300 rounded-lg bg-white font-bold"
                          />
                        </div>
                      </div>
                    </div>
                  );
                })}

                <button
                  type="button"
                  onClick={addRule}
                  className="w-full py-2.5 border-2 border-dashed border-slate-200 hover:border-indigo-400 text-indigo-600 rounded-xl text-xs font-bold transition-all flex items-center justify-center gap-1.5"
                >
                  <Plus className="w-4 h-4" />
                  Add Blueprint Rule
                </button>
              </div>
            </div>
          )}

          {/* ══════════ MODE C: Official GATE Full Mock Generator ══════════ */}
          {builderMode === 'full-mock' && (
            <div className="bg-white rounded-2xl border border-slate-200 shadow-xs p-6 space-y-6">
              <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-slate-100 pb-5">
                <div>
                  <div className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-full text-xs font-bold bg-amber-100 text-amber-900 border border-amber-200 mb-2">
                    <Sparkles className="w-3.5 h-3.5 text-amber-600" />
                    Official GATE Specification (100 Marks • 180 Minutes)
                  </div>
                  <h3 className="text-lg font-bold text-slate-900">Official GATE 65-Question Full Mock Paper</h3>
                  <p className="text-xs text-slate-500 mt-1 max-w-xl">
                    Follows the official GATE CBT blueprint with Section 1: General Aptitude (10 Qs / 15 Marks) and Section 2: Core Subject (55 Qs / 85 Marks).
                  </p>
                </div>

                <div className="text-right sm:border-l sm:border-slate-100 sm:pl-5 shrink-0">
                  <span className="text-[11px] font-bold text-slate-400 block uppercase tracking-wider">Exact Duration</span>
                  <span className="text-xl font-extrabold text-indigo-700">180 Mins (3h)</span>
                </div>
              </div>

              {/* Core Subject Filter Selection */}
              <div className="p-4 bg-slate-50 border border-slate-200 rounded-xl space-y-2">
                <label className="block text-xs font-bold text-slate-700">
                  Target Core Engineering Subject (Section 2)
                </label>
                <select
                  value={mockSubjectId}
                  onChange={(e) => setMockSubjectId(e.target.value ? Number(e.target.value) : '')}
                  className="w-full px-3 py-2 text-sm bg-white border border-slate-300 rounded-xl font-medium focus:ring-2 focus:ring-indigo-400 focus:outline-none"
                >
                  <option value="">All Available Core Subjects (Comprehensive Mock)</option>
                  {hierarchy
                    .filter((s) => !s.name.toLowerCase().includes('general aptitude'))
                    .map((s) => (
                      <option key={s.id} value={s.id}>
                        {s.name} ({s.topics.reduce((acc, t) => acc + (t._count?.questions || 0), 0)} Qs available)
                      </option>
                    ))}
                </select>
              </div>

              {/* Specification Breakdown Cards */}
              <div className="space-y-3">
                <span className="text-xs font-bold text-slate-500 uppercase tracking-wider block">
                  Syllabus Split &amp; Question Bank Availability
                </span>

                <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                  {/* Bucket 1: GA 1-Mark */}
                  <div className="p-3.5 bg-slate-50 border border-slate-200 rounded-xl space-y-1.5">
                    <div className="flex justify-between items-center text-xs">
                      <span className="font-bold text-slate-800">General Aptitude (1-Mark)</span>
                      <span className="font-mono text-indigo-700 font-bold">5 Qs (5 Marks)</span>
                    </div>
                    <div className="flex justify-between items-center text-[11px] text-slate-500">
                      <span>Available: {ga1m.length} Qs</span>
                      <span className={ga1m.length >= 5 ? 'text-emerald-600 font-bold' : 'text-amber-600 font-bold'}>
                        {ga1m.length >= 5 ? '✓ Ready' : `${5 - ga1m.length} short`}
                      </span>
                    </div>
                  </div>

                  {/* Bucket 2: GA 2-Mark */}
                  <div className="p-3.5 bg-slate-50 border border-slate-200 rounded-xl space-y-1.5">
                    <div className="flex justify-between items-center text-xs">
                      <span className="font-bold text-slate-800">General Aptitude (2-Mark)</span>
                      <span className="font-mono text-indigo-700 font-bold">5 Qs (10 Marks)</span>
                    </div>
                    <div className="flex justify-between items-center text-[11px] text-slate-500">
                      <span>Available: {ga2m.length} Qs</span>
                      <span className={ga2m.length >= 5 ? 'text-emerald-600 font-bold' : 'text-amber-600 font-bold'}>
                        {ga2m.length >= 5 ? '✓ Ready' : `${5 - ga2m.length} short`}
                      </span>
                    </div>
                  </div>

                  {/* Bucket 3: Core 1-Mark */}
                  <div className="p-3.5 bg-slate-50 border border-slate-200 rounded-xl space-y-1.5">
                    <div className="flex justify-between items-center text-xs">
                      <span className="font-bold text-slate-800">Core Subject (1-Mark)</span>
                      <span className="font-mono text-indigo-700 font-bold">25 Qs (25 Marks)</span>
                    </div>
                    <div className="flex justify-between items-center text-[11px] text-slate-500">
                      <span>Available: {core1m.length} Qs</span>
                      <span className={core1m.length >= 25 ? 'text-emerald-600 font-bold' : 'text-amber-600 font-bold'}>
                        {core1m.length >= 25 ? '✓ Ready' : `${25 - core1m.length} short`}
                      </span>
                    </div>
                  </div>

                  {/* Bucket 4: Core 2-Mark */}
                  <div className="p-3.5 bg-slate-50 border border-slate-200 rounded-xl space-y-1.5">
                    <div className="flex justify-between items-center text-xs">
                      <span className="font-bold text-slate-800">Core Subject (2-Mark)</span>
                      <span className="font-mono text-indigo-700 font-bold">30 Qs (60 Marks)</span>
                    </div>
                    <div className="flex justify-between items-center text-[11px] text-slate-500">
                      <span>Available: {core2m.length} Qs</span>
                      <span className={core2m.length >= 30 ? 'text-emerald-600 font-bold' : 'text-amber-600 font-bold'}>
                        {core2m.length >= 30 ? '✓ Ready' : `${30 - core2m.length} short`}
                      </span>
                    </div>
                  </div>
                </div>
              </div>

              {/* Status & Shortfall Alert */}
              {!isFull65Available && (
                <div className="p-4 bg-amber-50/80 border border-amber-200 rounded-xl text-xs space-y-1.5 text-amber-900">
                  <div className="flex items-center gap-2 font-bold text-amber-800">
                    <AlertCircle className="w-4 h-4 text-amber-600 shrink-0" />
                    <span>Question Bank Capacity Notice</span>
                  </div>
                  <p className="leading-relaxed">
                    Your Question Bank currently has <strong>{totalMockAvailable}</strong> matching questions (65 needed for full paper). You can generate a <strong>Best-Available Mock Test</strong> with all available questions, or add more questions in the Question Bank.
                  </p>
                </div>
              )}
            </div>
          )}
        </div>

        {/* ─── RIGHT PANEL: Live Test Paper Summary & Actions ─── */}
        <aside className="w-full lg:w-96 shrink-0 space-y-4">
          <div className="bg-white rounded-2xl border border-slate-200 shadow-sm p-5 space-y-5 sticky top-20">
            <div>
              <span className="text-xs uppercase font-extrabold tracking-wider text-indigo-600 block">
                Test Paper Blueprint
              </span>
              <h3 className="text-lg font-bold text-slate-800 mt-1">Live Test Configuration</h3>
            </div>

            {/* Test Title & Description Inputs */}
            <div className="space-y-3">
              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">Test Title</label>
                <input
                  type="text"
                  value={testTitle}
                  onChange={(e) => setTestTitle(e.target.value)}
                  className="w-full px-3 py-2 text-sm border border-slate-300 rounded-xl focus:ring-2 focus:ring-indigo-400 focus:outline-none font-semibold text-slate-800"
                />
              </div>

              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">Description / Notes</label>
                <textarea
                  rows={2}
                  value={testDesc}
                  onChange={(e) => setTestDesc(e.target.value)}
                  className="w-full px-3 py-2 text-xs border border-slate-300 rounded-xl focus:ring-2 focus:ring-indigo-400 focus:outline-none text-slate-600"
                />
              </div>

              {/* Mode Selection */}
              <div>
                <label className="block text-xs font-bold text-slate-700 mb-1">Delivery Mode</label>
                <div className="grid grid-cols-2 gap-2">
                  <button
                    type="button"
                    onClick={() => setTestMode('exam')}
                    className={`py-2 px-3 rounded-xl text-xs font-bold border transition-all ${
                      testMode === 'exam'
                        ? 'border-indigo-600 bg-indigo-50 text-indigo-700'
                        : 'border-slate-200 text-slate-600 hover:bg-slate-50'
                    }`}
                  >
                    Exam Mode (CBT)
                  </button>
                  <button
                    type="button"
                    onClick={() => setTestMode('practice')}
                    className={`py-2 px-3 rounded-xl text-xs font-bold border transition-all ${
                      testMode === 'practice'
                        ? 'border-indigo-600 bg-indigo-50 text-indigo-700'
                        : 'border-slate-200 text-slate-600 hover:bg-slate-50'
                    }`}
                  >
                    Practice Mode
                  </button>
                </div>
              </div>
            </div>

            {/* Live Metrics Grid */}
            <div className="border-t border-slate-100 pt-4 space-y-3">
              <span className="text-xs font-bold text-slate-500 block">Computed Test Metrics</span>

              <div className="grid grid-cols-2 gap-2 text-center">
                <div className="bg-slate-50 p-2.5 rounded-xl border border-slate-100">
                  <span className="text-xs text-slate-400 block font-medium">Questions</span>
                  <span className="text-xl font-bold text-slate-800">
                    {builderMode === 'full-mock'
                      ? isFull65Available
                        ? 65
                        : totalMockAvailable
                      : builderMode === 'manual'
                      ? totalQuestions
                      : rules.reduce((s, r) => s + r.count, 0)}
                  </span>
                </div>
                <div className="bg-slate-50 p-2.5 rounded-xl border border-slate-100">
                  <span className="text-xs text-slate-400 block font-medium">Total Marks</span>
                  <span className="text-xl font-bold text-indigo-600">
                    {builderMode === 'full-mock'
                      ? `${
                          Math.min(5, ga1m.length) * 1 +
                          Math.min(5, ga2m.length) * 2 +
                          Math.min(25, core1m.length) * 1 +
                          Math.min(30, core2m.length) * 2
                        } M`
                      : builderMode === 'manual'
                      ? `${totalMarks} M`
                      : 'Auto-computed'}
                  </span>
                </div>
              </div>

              <div className="bg-slate-50 p-3 rounded-xl border border-slate-100 flex items-center justify-between text-xs">
                <span className="text-slate-500 flex items-center gap-1.5 font-medium">
                  <Clock className="w-4 h-4 text-indigo-600" />
                  Auto-Calculated Duration:
                </span>
                <span className="font-bold text-slate-800">
                  {builderMode === 'full-mock'
                    ? isFull65Available
                      ? '180 Mins (3h)'
                      : formatDurationHuman(calculateDuration(totalMockAvailable))
                    : builderMode === 'manual'
                    ? formatDurationHuman(totalDuration)
                    : formatDurationHuman(
                        calculateDuration(rules.reduce((s, r) => s + r.count, 0))
                      )}
                </span>
              </div>

              {/* Type breakdown if manual mode */}
              {builderMode === 'manual' && totalQuestions > 0 && (
                <div className="flex items-center gap-1.5 text-xs">
                  <span className="px-2 py-0.5 rounded bg-blue-100 text-blue-800 font-bold">
                    {typeCounts.MCQ} MCQ
                  </span>
                  <span className="px-2 py-0.5 rounded bg-purple-100 text-purple-800 font-bold">
                    {typeCounts.MSQ} MSQ
                  </span>
                  <span className="px-2 py-0.5 rounded bg-emerald-100 text-emerald-800 font-bold">
                    {typeCounts.NAT} NAT
                  </span>
                </div>
              )}

              {/* Subject Distribution */}
              {builderMode === 'manual' && subjectCounts.length > 0 && (
                <div className="space-y-1 pt-1">
                  <span className="text-[11px] font-bold text-slate-500 block">Subject Mix:</span>
                  <div className="flex flex-wrap gap-1">
                    {subjectCounts.map(([subj, count]) => (
                      <span
                        key={subj}
                        className="px-2 py-0.5 rounded-md text-[11px] font-semibold bg-indigo-50 text-indigo-700 border border-indigo-100"
                      >
                        {subj}: {count}
                      </span>
                    ))}
                  </div>
                </div>
              )}
            </div>

            {/* Launch & Export CTA Buttons */}
            <div className="border-t border-slate-100 pt-4 space-y-2">
              <button
                type="button"
                disabled={generating || (builderMode === 'manual' && totalQuestions === 0) || (builderMode === 'full-mock' && totalMockAvailable === 0)}
                onClick={handleLaunchTest}
                className="w-full py-3 bg-indigo-600 hover:bg-indigo-700 text-white font-bold rounded-xl shadow-sm transition-all flex items-center justify-center gap-2 disabled:opacity-50 cursor-pointer text-sm"
              >
                <Play className="w-4 h-4 fill-current" />
                {generating ? (
                  'Synthesizing Mock Test...'
                ) : builderMode === 'full-mock' ? (
                  isFull65Available ? (
                    'Launch Official GATE Full Mock (65 Qs) →'
                  ) : (
                    'Generate Best-Available Mock →'
                  )
                ) : (
                  'Launch Test Directly →'
                )}
              </button>

              <button
                type="button"
                disabled={generating || (builderMode === 'manual' && totalQuestions === 0) || (builderMode === 'full-mock' && totalMockAvailable === 0)}
                onClick={handleExportJSON}
                className="w-full py-2.5 bg-slate-100 hover:bg-slate-200 text-slate-700 font-bold rounded-xl transition-all flex items-center justify-center gap-2 text-xs disabled:opacity-50 cursor-pointer"
              >
                <Download className="w-3.5 h-3.5" />
                Export Custom Test (.json)
              </button>
            </div>
          </div>
        </aside>
      </div>

      {/* 0% Fee UPI Paywall Modal */}
      <PaymentModal
        isOpen={showPaymentModal}
        onClose={() => setShowPaymentModal(false)}
        onSuccess={() => {
          setShowPaymentModal(false);
          // auto launch test on successful activation
          handleLaunchTest();
        }}
      />
    </div>
  );
}
